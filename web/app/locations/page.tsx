function draftOf(location: Location): Draft {
  return {
    ...EMPTY_DRAFT,
    id: location.id,
    name: location.name,
    slug: location.slug,
    address: location.address ?? '',
    active: location.active,
    lat: location.lat,
    lng: location.lng,
    clientChoice: location.client_id === null ? NONE : String(location.client_id),
    contactChoice: location.contact_id === null ? NONE : String(location.contact_id),
    monthly:
      location.monthly_contract_cents === null
        ? ''
        : centsToPlainEuros(location.monthly_contract_cents),
    // Only whole hours can be typed here, so a stored value that is not a whole hour cannot
    // be shown in this field without changing it. It is left empty and the exact stored
    // value is named in a hint next to the field instead of being silently rounded.
    targetHours:
      location.target_minutes_per_month !== null && location.target_minutes_per_month % 60 === 0
        ? String(location.target_minutes_per_month / 60)
        : '',
  }
}

