/**
 * Buildings screen — where a building is, who pays for it, what we charge, how much time we
 * agreed to and how much we have actually spent this month, the string that goes on its NFC
 * tag, and the link its client can be given.
 *
 * The tag URI is the load-bearing part. A tag carries `https://…/t?l=<location uuid>`
 * (decision-21): the UUID is the identity, generated by the database, and the slug is only a
 * human label. A wrong string on a sticker is discovered when a worker taps it and nothing
 * happens, and fixing it costs a site visit — so the full URI stays ON THE ROW, verbatim,
 * never elided and never one click away behind an overlay.
 *
 * The client and the point of contact can both be CREATED FROM THE SAME DRAWER. Sending the
 * director to two other screens before they can file one building is the friction that makes
 * a non-technical user stop using the panel; /clients/ exists for tidying up afterwards and
 * is never a prerequisite. It is a disclosure INSIDE this drawer and deliberately NOT a
 * second drawer on top of the first (owner, explicitly): a focus trap inside a focus trap is
 * a bug farm.
 *
 * Deactivation is soft, always: shifts reference buildings and the history has to survive.
 * One client component with `useState` + `fetch`, because this bundle is a static export
 * (decision-16) and no server component may fetch this data.
 */

/** Mirrors v.slug() in server/lib/validate.js. The server decides for real. */
const SLUG_RE = /^[a-z0-9][a-z0-9_-]*$/
/** Shape check only, mirroring v.optionalEmail(). */
const EMAIL_RE = /^[^\s@,]+@[^\s@,.]+(\.[^\s@,.]+)+$/
/** Mirrors v.optionalPhone(): digits and separators, no letters. */
const PHONE_RE = /^[0-9+()/.\s-]+$/
/**
 * Whole hours only.
 *
 * ponytail: the column stores minutes, and the form offers hours without a fraction. Every
 * target the director quoted is a round number of hours a month, and integer hours convert
 * to minutes exactly — no float multiplication anywhere near a number that later gets
 * subtracted from recorded time. Upgrade path when a 37.5 h contract appears: accept one
 * decimal place and convert tenths to 6-minute steps, still integer-only.
 */
const HOURS_RE = /^\d{1,4}$/
/** v.optionalMinutes() ceiling, 446 400 minutes, expressed in hours. */
const MAX_TARGET_HOURS = 7440

/** '' = none, 'new' = create it inline, anything else = that row's id. */
