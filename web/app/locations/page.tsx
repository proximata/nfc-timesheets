  /**
   * Clipboard access fails on an insecure origin and can be refused by the browser. That is
   * not fatal here: the string is on screen in full, so the fallback is to say so and let
   * the admin select it by hand rather than leave them believing a copy happened.
   */
  async function copy(text: string, okText: string, failText: string) {
    try {
      await navigator.clipboard.writeText(text)
      setNotice({ ok: true, text: okText })
    } catch {
      setNotice({ ok: false, text: failText })
    }
  }

