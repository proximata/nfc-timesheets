--
-- ponytail: no migration framework. Plain numbered .sql files applied by db/migrate.js
--   (a ~15-line runner over `psql`). Ceiling: no down-migrations, no checksum
--   verification, no branching/merge story. Upgrade path if we ever outgrow it:
--   node-pg-migrate — it also drives plain SQL files, so these files carry over.
--
-- CONSTRAINT ON THIS FILE AND EVERY FUTURE MIGRATION:
--   Do NOT write BEGIN/COMMIT here. migrate.js runs each file with `psql -1`,
