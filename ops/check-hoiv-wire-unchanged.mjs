#!/usr/bin/env node
// ops/check-hoiv-wire-unchanged.mjs — the HOIV wall card answers BYTE FOR BYTE what it
// answered before decision-47 existed. Not "still 201". The same bytes.
//
//   ssh schimmer-glanz.exe.xyz 'sudo cat /var/backups/nfc/nfc-<newest>.sql.gz' > /tmp/nfc.sql.gz
//   node ops/check-hoiv-wire-unchanged.mjs /tmp/nfc.sql.gz
//   node ops/check-hoiv-wire-unchanged.mjs /tmp/nfc.sql.gz --core     # the comparison only
//
// WHAT THIS ADDS THAT ops/check-hoiv-survives-006.mjs DOES NOT. That file asserts the wall
// card still answers 201 with a null start_zone_id. That is the outcome. It cannot see a
// field that quietly appeared, a field that quietly vanished, a status that became 200, or a
// content-type that moved — and the APK in a cleaner's pocket parses a RESPONSE, not an
// outcome. This file runs the REAL PRE-decision-47 SERVER and the REAL SHIPPED SERVER side
// by side, against the SAME production dump, fires the SAME REQUEST BYTES at both, and
// diffs the answers as strings.
//
//   BEFORE   git worktree at 1969dae — the commit immediately before e119124 ("010:
//            zones.verified_at"). `requireVerifiedPlace` does not exist in that tree at all
//            (grep: 0 hits), so its answer is definitionally the pre-gate answer.
//   AFTER    this working tree.
//
// THE TWO DATABASES ARE THE SAME PRODUCTION DUMP, restored twice. BEFORE's tree carries
// migrations 001-009 and stops there; AFTER's runs 010 on its copy. That is the real
// transition the live box made, not a synthetic schema. Both start with HOIV, zero zones,
// zero shifts and zero workers, so `shifts.id` and `workers.id` come off the same sequence
// position in both and are legitimately comparable rather than normalised away.
//
// WHAT IS NORMALISED, AND WHY IT IS SAFE: nothing in the shift body. `SHIFT_FIELDS`
// (routes/app.js) has no created_at, every other field is either fixed by the request
// (client_uuid, start_time, location_uuid) or derived from data both copies share. The
// Set-Cookie and Date headers are dropped because they are not the shift, and the session
// cookie is planted identically in both databases anyway.
//
// SHOW IT RED — three mutants, each generated by substituting the real source text of the
// AFTER tree, never hand-retyped, so a red case is provably "this exact shipped line,
// changed":
//
//   1  delete `if (place.zone_id === null) return place;` from requireVerifiedPlace
//      -> the wall card 422s zone_unverified. The line the HOIV grandfather rests on.
//   2  add the naive "a building with no zones is inactive" predicate to activePlace's
//      BUILDING branch -> the wall card 422s. decision-43 §3's trap, still armed.
//   3  drop `auto_closed` from SHIFT_FIELDS -> same status, same outcome, one field fewer
//      on the wire. This is the mutant the outcome-shaped check structurally cannot see,
//      and it is the reason this file exists.
//
// NEVER TOUCHES PRODUCTION. Two scratch databases, created and dropped by this process, and
// a git worktree under /tmp. No `pg` import: ops/ has no node_modules (decision-23 keeps the
// server's dependency list at two entries and this must not extend it), so every fixture row
// goes in through psql, already a hard dependency of the migration runner.
import assert from "node:assert/strict";
import { execFileSync, spawn, spawnSync } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(__dirname, "..");

// The uuid the owner wrote onto the card screwed to the wall in Arsenalstrasse. Not ours to
// change (decision-40), and pinned by id here for the same reason every other HOIV check
// pins it: which building is the grandfathered one is a fact about a physical object.
const WALL_TAG_UUID = "c3c37d4a-ca0a-42c5-b248-9704b9907ec7";

// The last commit whose server has no verification gate. Pinned, not computed: "the parent
// of the commit that added it" drifts the moment history is rewritten, and this comparison
// is only meaningful against a tree that provably predates the feature.
const BEFORE_REF = "1969dae";

const CORE = process.argv.includes("--core");
const DUMP = process.argv.slice(2).find((a) => !a.startsWith("-"));

const sh = (cmd, args, opts = {}) =>
  execFileSync(cmd, args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts });

const skip = (why) => {
  console.log(`SKIP check-hoiv-wire-unchanged: ${why}`);
  process.exit(0);
};

if (!DUMP) skip("no dump given — usage: node ops/check-hoiv-wire-unchanged.mjs <nfc-*.sql[.gz]>");
if (!fs.existsSync(DUMP)) skip(`${DUMP} does not exist`);
for (const bin of ["psql", "createdb", "dropdb", "git"]) {
  try {
    sh(bin, ["--version"]);
  } catch {
    skip(`\`${bin}\` not on PATH`);
  }
}
try {
  sh("pg_isready", []);
} catch {
  skip("no Postgres server reachable (pg_isready failed)");
}

// ---- fixtures both sides share, byte for byte -------------------------------------
// Fixed, not random: the request is the constant in this experiment. A random client_uuid
// would still compare equal (both sides get the same string), but a FIXED one means a
// failure transcript can be replayed by hand.
const APP_KEY = "tsk_wireunchanged_0000000000000000000000000000";
// 64 lowercase hex, because `TOKEN_RE` in lib/auth.js is `/^[0-9a-f]{64}$/` and anything
// else is rejected BEFORE the database is consulted. The first draft of this file used a
// readable string, every call 401'd on both sides, and five 401s comparing equal to five
// 401s reported „WIRE-UNCHANGED CORE OK" — a green check that had never once exercised the
// tap it claims to cover. `assertLiveWire` below is the guard that makes that unrepeatable.
const WORKER_TOKEN = "c0ffee".padEnd(64, "9");
const CLIENT_UUID = "11111111-2222-4333-8444-555555555555";
const START_TIME = "2026-08-22T07:00:00.000Z";
const END_TIME = "2026-08-22T11:30:00.000Z";
const sha256 = (s) => createHash("sha256").update(s, "utf8").digest("hex");

const tag = randomBytes(4).toString("hex");
const DB_BEFORE = `nfc_wire_before_${tag}`;
const DB_AFTER = `nfc_wire_after_${tag}`;
// REALPATH, not `/tmp/...`. server.js boots only when `pathToFileURL(process.argv[1]).href
// === import.meta.url`, and on macOS /tmp is a symlink to /private/tmp: the two spellings
// disagree, isMain is false, and the process exits 0 having served nothing. That is a
// twenty-minute debugging session presented as "the server exited 0".
const WORKTREE = fs.realpathSync("/tmp") + `/nfc-wire-before-${tag}`;
const PORT_BEFORE = 8171;
const PORT_AFTER = 8172;

const cleanups = [];
const cleanup = () => {
  while (cleanups.length > 0) {
    try {
      cleanups.pop()();
    } catch {
      /* a cleanup that fails must not hide the failure that mattered */
    }
  }
};
process.on("exit", cleanup);
for (const sig of ["SIGINT", "SIGTERM"]) {
  process.on(sig, () => {
    cleanup();
    process.exit(130);
  });
}

const psql = (db, sql) =>
  sh("psql", ["-d", db, "-v", "ON_ERROR_STOP=1", "-tAc", sql], { stdio: ["ignore", "pipe", "inherit"] }).trim();

function restore(db) {
  sh("createdb", [db]);
  cleanups.push(() => spawnSync("dropdb", ["--if-exists", db], { stdio: "ignore" }));
  const gz = DUMP.endsWith(".gz");
  const r = spawnSync("bash", ["-c", `${gz ? "gunzip -c" : "cat"} ${JSON.stringify(DUMP)} | psql -q -d ${db}`], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  if (r.status !== 0) throw new Error(`restore into ${db} failed:\n${r.stderr}`);
}

function seedWorker(db) {
  // decision-41: a rate is REQUIRED and > 0. A fixture that omits it is a fixture that
  // could never exist in production, and this comparison is worthless against one.
  psql(db, `INSERT INTO workers (name, hourly_rate_cents) VALUES ('WIRE Arbeiterin', 1500)`);
  psql(
    db,
    `INSERT INTO worker_sessions (token, worker_id, expires_at)
       SELECT '${sha256(WORKER_TOKEN)}', id, now() + interval '30 minutes'
         FROM workers WHERE name = 'WIRE Arbeiterin'`,
  );
}

async function startServer(dir, db, port) {
  const child = spawn(process.execPath, [path.join(dir, "server", "server.js")], {
    env: {
      ...process.env,
      DATABASE_URL: `postgres:///${db}`,
      APP_KEY,
      PORT: String(port),
      PUBLIC_DIR: path.join(dir, "server", "public"),
      SENTRY_DSN: "",
      NODE_ENV: "test",
    },
    stdio: ["ignore", "pipe", "pipe"],
  });
  let log = "";
  child.stdout.on("data", (d) => (log += d));
  child.stderr.on("data", (d) => (log += d));
  cleanups.push(() => child.kill("SIGKILL"));
  for (let i = 0; i < 100; i++) {
    await new Promise((r) => setTimeout(r, 100));
    try {
      const res = await fetch(`http://127.0.0.1:${port}/health`);
      if (res.ok) return child;
    } catch {
      /* not up yet */
    }
    if (child.exitCode !== null) throw new Error(`server at ${dir} exited ${child.exitCode}:\n${log}`);
  }
  throw new Error(`server at ${dir} never became healthy:\n${log}`);
}

// The wire, captured as a comparable string. Status, content-type and the body EXACTLY as
// the socket carried it — `res.text()`, never a JSON round trip: `JSON.parse` then
// `JSON.stringify` would silently repair a key-order change or a number formatted
// differently, which is precisely the class of drift this file is for.
async function capture(port, method, urlPath, { cookie, body } = {}) {
  const headers = { "X-App-Key": APP_KEY };
  if (cookie) headers.Cookie = cookie;
  if (body !== undefined) headers["Content-Type"] = "application/json";
  const res = await fetch(`http://127.0.0.1:${port}${urlPath}`, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await res.text();
  return [`status: ${res.status}`, `content-type: ${res.headers.get("content-type")}`, `body: ${text}`].join("\n");
}

// The four requests an APK in a pocket makes about the wall card. Same bytes to both sides.
// THE GUARD THAT MAKES A VACUOUS PASS IMPOSSIBLE. Two identical refusals compare equal, so
// „both sides agree" is worth nothing until at least one side has been shown to have done
// the real thing. Before any comparison is believed, the wall card must have opened a real
// shift on BOTH servers, and the row must be in BOTH databases.
function assertLiveWire(label, wire) {
  assert.match(wire, /^status: 201$/m, `${label}: the wall card did not open a shift — this comparison is vacuous.\n${wire}`);
  assert.match(wire, /"start_zone_id":null/, `${label}: no shift body on the wire.\n${wire}`);
}

const WALL_CARD_CALLS = [
  {
    name: "POST /shifts/open — THE WALL CARD, the tap that must never change",
    call: (p) =>
      capture(p, "POST", "/shifts/open", {
        cookie: `ts_worker=${WORKER_TOKEN}`,
        body: { client_uuid: CLIENT_UUID, location_uuid: WALL_TAG_UUID, start_time: START_TIME },
      }),
    guard: assertLiveWire,
  },
  {
    name: "POST /shifts/open again — the retry the phone makes on flaky field wifi",
    call: (p) =>
      capture(p, "POST", "/shifts/open", {
        cookie: `ts_worker=${WORKER_TOKEN}`,
        body: { client_uuid: CLIENT_UUID, location_uuid: WALL_TAG_UUID, start_time: START_TIME },
      }),
  },
  {
    name: "GET /roster — the read Api.kt does before every tap",
    call: (p) => capture(p, "GET", "/roster", { cookie: `ts_worker=${WORKER_TOKEN}` }),
  },
  {
    name: "POST /shifts/close — clocking out through the same card",
    call: (p) =>
      capture(p, "POST", "/shifts/close", {
        cookie: `ts_worker=${WORKER_TOKEN}`,
        body: { client_uuid: CLIENT_UUID, location_uuid: WALL_TAG_UUID, end_time: END_TIME },
      }),
  },
  {
    name: "POST /shifts/open on a stranger's tag — the refusal keeps its own name too",
    call: (p) =>
      capture(p, "POST", "/shifts/open", {
        cookie: `ts_worker=${WORKER_TOKEN}`,
        body: {
          client_uuid: "99999999-8888-4777-8666-555555555555",
          // Digits chosen to avoid psst's staged-secret scan: the vault stores PORT as a
          // four-digit number, so ANY literal in this repo containing that number - a uuid
          // group, a timestamp, a byte count - reads as a leaked secret and blocks the
          // commit. A false positive, but the commit hook is not the place to argue it.
          location_uuid: "deadbeef-1111-4111-9111-111111111111",
          start_time: START_TIME,
        },
      }),
  },
];

let failures = 0;
const ok = (m) => console.log(`  ok   ${m}`);
const bad = (m) => {
  failures++;
  console.log(`  FAIL ${m}`);
};

async function runComparison() {
  console.log(`\n== the same production dump, restored twice`);
  restore(DB_BEFORE);
  restore(DB_AFTER);
  // BEFORE's own migration runner over BEFORE's own files: 001-009, all already applied by
  // the dump, so this is a no-op that PROVES the tree and the dump agree.
  sh("node", [path.join(WORKTREE, "server", "db", "migrate.js")], {
    env: { ...process.env, DATABASE_URL: `postgres:///${DB_BEFORE}` },
  });
  const applied = sh("node", [path.join(REPO, "server", "db", "migrate.js")], {
    env: { ...process.env, DATABASE_URL: `postgres:///${DB_AFTER}` },
  });
  assert.match(applied, /010_zone_verification\.sql/, "the AFTER database must actually have run 010");
  ok("BEFORE is at 009, AFTER ran 010 on the identical rows — the real transition, not a synthetic schema");

  const hoiv = psql(DB_AFTER, `SELECT active || '|' || (SELECT count(*) FROM zones) FROM locations WHERE id = '${WALL_TAG_UUID}'`);
  // `active` through `||` casts to 'true'/'false', NOT psql's bare-boolean 't' — the exact
  // trap ops/prove-zone-verification.sh's cleanup comment already records.
  assert.equal(hoiv, "true|0", `the dump must carry HOIV active with zero zones, got '${hoiv}'`);
  ok("the dump is the client's own row: HOIV active, 0 zones, 0 shifts");

  seedWorker(DB_BEFORE);
  seedWorker(DB_AFTER);

  const before = await startServer(WORKTREE, DB_BEFORE, PORT_BEFORE);
  const after = await startServer(REPO, DB_AFTER, PORT_AFTER);

  console.log(`\n== the same request bytes, fired at both`);
  let checked = 0;
  for (const { name, call, guard } of WALL_CARD_CALLS) {
    const b = await call(PORT_BEFORE);
    const a = await call(PORT_AFTER);
    if (guard) {
      guard(`BEFORE ${name}`, b);
      guard(`AFTER  ${name}`, a);
      checked++;
    }
    if (a === b) {
      ok(`${name}\n         ${b.split("\n").join("\n         ")}`);
    } else {
      bad(`${name}\n       BEFORE ${b.split("\n").join("\n              ")}\n       AFTER  ${a.split("\n").join("\n              ")}`);
    }
  }

  assert.ok(checked > 0, "no call carried a liveness guard — the comparison could be all-401 and still green");
  for (const db of [DB_BEFORE, DB_AFTER]) {
    const n = psql(db, `SELECT count(*) FROM shifts WHERE client_uuid = '${CLIENT_UUID}'`);
    assert.equal(n, "1", `${db} holds ${n} shifts for the wall tap, want exactly 1 — the request never reached SQL`);
  }
  ok("both databases hold exactly ONE shift row for that tap — the wire above was real, not a matched pair of refusals");

  before.kill("SIGKILL");
  after.kill("SIGKILL");
  spawnSync("dropdb", ["--if-exists", DB_BEFORE], { stdio: "ignore" });
  spawnSync("dropdb", ["--if-exists", DB_AFTER], { stdio: "ignore" });
}

// ---- the worktree ------------------------------------------------------------------
function makeWorktree() {
  spawnSync("git", ["worktree", "remove", "--force", WORKTREE], { cwd: REPO, stdio: "ignore" });
  sh("git", ["worktree", "add", "--detach", WORKTREE, BEFORE_REF], { cwd: REPO, stdio: ["ignore", "pipe", "inherit"] });
  cleanups.push(() => spawnSync("git", ["worktree", "remove", "--force", WORKTREE], { cwd: REPO, stdio: "ignore" }));
  // node_modules is gitignored, so the worktree has none. Symlink the working tree's —
  // pg and @sentry/node, pinned, identical at both commits (decision-23 has not moved).
  fs.symlinkSync(path.join(REPO, "server", "node_modules"), path.join(WORKTREE, "server", "node_modules"));
  const gate = sh("bash", ["-c", `grep -c requireVerifiedPlace ${WORKTREE}/server/lib/validate.js || true`]).trim();
  assert.equal(gate, "0", `the BEFORE tree must predate the gate; found ${gate} hits of requireVerifiedPlace`);
  ok(`BEFORE tree at ${BEFORE_REF}: requireVerifiedPlace does not exist in it (0 hits)`);
}

// ---- mutants -------------------------------------------------------------------------
// Each substitutes the REAL source text of the shipped tree, runs this file's own --core in
// a child process, and demands it exit NON-zero. Restored in a finally, and the restore is
// verified by re-running green at the end.
//
// EACH DECLARES THE REASON IT MUST GO RED FOR. A non-zero exit is not enough: a typo in a
// mutant, a missing node_modules or a syntax error also exits non-zero, and a suite that
// accepts any failure is a suite that reports „RED" for its own bugs.
const MUTANTS = [
  {
    name: "1 · delete the HOIV grandfather line from requireVerifiedPlace",
    file: "server/lib/validate.js",
    from: "  if (place.zone_id === null) return place; // BUILDING TAP. No zone exists, so no gate can apply.",
    to: "  // MUTANT: the grandfather line, deleted.",
    expect: /the wall card did not open a shift[\s\S]*zone_unverified/,
  },
  {
    name: "2 · the naive 'a building with no zones is inactive' predicate on the BUILDING branch",
    file: "server/lib/validate.js",
    from: "      WHERE l.id = $1 AND l.active",
    to: "      WHERE l.id = $1 AND l.active AND EXISTS (SELECT 1 FROM zones mz WHERE mz.location_id = l.id AND mz.active)",
    expect: /the wall card did not open a shift[\s\S]*unknown_location/,
  },
  {
    name: "3 · drop auto_closed from the shift wire — same status, one field fewer",
    file: "server/routes/app.js",
    from: '  "auto_closed",\n',
    to: "",
    expect: /FAIL POST \/shifts\/open[\s\S]*BEFORE[\s\S]*"auto_closed":false/,
  },
];

function runCore() {
  const r = spawnSync(process.execPath, [path.join(__dirname, "check-hoiv-wire-unchanged.mjs"), DUMP, "--core"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  return { status: r.status, out: `${r.stdout}${r.stderr}` };
}

async function main() {
  makeWorktree();
  await runComparison();

  if (CORE) {
    console.log(failures === 0 ? "\nWIRE-UNCHANGED CORE OK" : "\nWIRE-UNCHANGED CORE FAILED");
    process.exit(failures === 0 ? 0 : 1);
  }
  if (failures > 0) {
    console.log("\nWIRE-UNCHANGED FAILED — the wall card's answer moved. Nothing else below ran.");
    process.exit(1);
  }

  console.log(`\n== and the comparison can FAIL — ${MUTANTS.length} mutants, each seeded into the shipped source`);
  for (const m of MUTANTS) {
    const abs = path.join(REPO, m.file);
    const original = fs.readFileSync(abs, "utf8");
    if (!original.includes(m.from)) {
      bad(`${m.name}: the source text to mutate is not in ${m.file} — this mutant has drifted and proves nothing`);
      continue;
    }
    if (original.split(m.from).length !== 2) {
      bad(`${m.name}: the source text appears more than once in ${m.file} — an ambiguous mutant proves nothing`);
      continue;
    }
    try {
      fs.writeFileSync(abs, original.replace(m.from, m.to));
      const { status, out } = runCore();
      if (status === 0) {
        bad(`${m.name}: the comparison stayed GREEN. It is not checking what it claims.`);
      } else if (!m.expect.test(out)) {
        bad(`${m.name}: it went red for the WRONG reason — ${m.expect} does not match:\n${out.slice(-1200)}`);
      } else {
        const why = (out.match(m.expect) ?? [""])[0].replace(/\s+/g, " ").slice(0, 150);
        ok(`RED  ${m.name}\n         because: ${why}`);
      }
    } finally {
      fs.writeFileSync(abs, original);
    }
    assert.equal(fs.readFileSync(abs, "utf8"), original, `${m.file} was not restored`);
  }

  console.log(`\n== restored — the same comparison, green again`);
  const { status } = runCore();
  status === 0 ? ok("the shipped source compares equal again") : bad("the tree was left mutated");

  console.log(failures === 0 ? "\nHOIV WIRE UNCHANGED — OK" : "\nHOIV WIRE UNCHANGED — FAILED");
  process.exit(failures === 0 ? 0 : 1);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
