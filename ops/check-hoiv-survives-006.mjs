#!/usr/bin/env node
// ops/check-hoiv-survives-006.mjs — decision-43 §3, proved against the CLIENT'S OWN ROW.
//
//   ssh schimmer-glanz.exe.xyz 'sudo cat /var/backups/nfc/nfc-<newest>.sql.gz' > /tmp/nfc.sql.gz
//   node ops/check-hoiv-survives-006.mjs /tmp/nfc.sql.gz
//
// THE QUESTION THIS ANSWERS. decision-37 (accepted, now superseded) was written alongside an
// owner rule that reads, naively, "a building with no zones is INACTIVE". HOIV is the client's
// ONLY building. It has ZERO zones, and its own BUILDING uuid is written on a card screwed to
// a wall in Arsenalstrasse — a card nobody can rewrite from here. Wire that rule into
// resolution and the card 422s on the day migration 006 lands, permanently, with no site visit
// able to fix it.
//
// decision-47 ADDS A SECOND WAY TO KILL THE SAME CARD, and this file is now the proof for
// both. 010 makes a zone untappable until an operator test-scanned it (`zones.verified_at`).
// A building tap has NO zone, so the gate must be unreachable from it — not "we did not wire
// it up", but structurally: `activePlace`'s building branch emits NULL LITERALS for both zone
// columns, and `requireVerifiedPlace` returns unconditionally on a NULL zone_id. Phase 1 taps
// the wall card BOTH with HOIV unzoned AND with an UNVERIFIED zone sitting under it; phase 2
// mutates each of those two properties and demands the tap go RED.
//
// decision-43 §3 rules that `zone_state` is PRESENTATION ONLY: grey pin, a sentence, and
// nothing else. This file is the proof that the code agrees, and that the proof can FAIL:
//
//   PHASE 1 (--core)  restore the real dump, apply 006/007/008, and assert against the actual
//                     HOIV row that it stays ACTIVE, keeps both coordinates, reports
//                     zone_state 'unzoned' WITH active true, and still answers 201 to the
//                     shipped APK's POST /shifts/open using the uuid off the card.
//   PHASE 2           mutate the SERVER, one site at a time, into the two shapes the naive
//                     rule would produce, re-run phase 1 in a child process, and demand it go
//                     RED. Then restore and demand GREEN again.
//
// The mutants are generated by substituting the real source text — never hand-retyped — so a
// red case is provably "this exact line, changed" and cannot drift from what ships.
//
// NEVER touches production. The scratch database is created and dropped by this process.
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// NO `pg` IMPORT HERE, on purpose. This file lives in ops/, which has no node_modules; the
// driver is server/'s (decision-23 keeps that list at two entries and this must not extend
// it). Every fixture row below therefore goes in through psql, which is already a hard
// dependency of this project's migration runner.

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SERVER = path.join(__dirname, "..", "server");
const MIGRATE = path.join(SERVER, "db", "migrate.js");

// The uuid the owner wrote onto the card and mounted at the only live building. Not ours to
// change (decision-40): the tag host is permanent because this string is on a wall.
const WALL_TAG_UUID = "c3c37d4a-ca0a-42c5-b248-9704b9907ec7";

const CORE = process.argv.includes("--core");
const DUMP = process.argv.find((a) => a !== "--core" && !a.startsWith("-") && a !== process.argv[0] && a !== process.argv[1]);

const sh = (cmd, args, opts = {}) =>
  execFileSync(cmd, args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts });

const skip = (why) => {
  console.log(`SKIP check-hoiv-survives-006: ${why}`);
  process.exit(0);
};

if (!DUMP) skip("no dump given — usage: node ops/check-hoiv-survives-006.mjs <nfc-*.sql[.gz]>");
if (!fs.existsSync(DUMP)) skip(`${DUMP} does not exist`);
for (const bin of ["psql", "createdb", "dropdb"]) {
  try {
    sh(bin, ["--version"]);
  } catch {
    skip(`\`${bin}\` not on PATH`);
  }
}
try {
  sh("pg_isready", []);
} catch {
  skip("no Postgres server reachable (pg_isready failed)");
}

// =========================================================================================
// PHASE 1 — the assertions, against the restored production database
// =========================================================================================
async function core() {
  const DB_NAME = `nfc_hoiv_${process.pid}`;
  const DATABASE_URL = `postgres:///${DB_NAME}`;
  const APP_KEY = "hoiv-survives-check-key";
  const q = (sql) => sh("psql", [DATABASE_URL, "-v", "ON_ERROR_STOP=1", "-q", "-t", "-A", "-c", sql]).trim();

  const ok = (m) => console.log(`  ok   ${m}`);
  let server;
  sh("createdb", [DB_NAME]);
  try {
    const sql = DUMP.endsWith(".gz") ? sh("gunzip", ["-c", DUMP]) : fs.readFileSync(DUMP, "utf8");
    sh("psql", [DATABASE_URL, "-v", "ON_ERROR_STOP=1", "-q", "-f", "-"], { input: sql, stdio: ["pipe", "pipe", "pipe"] });

    // The one ops step this file is not about (it has its own harness,
    // ops/check-delete-worker.mjs) — 006 refuses while a rate-less worker exists.
    sh("psql", [DATABASE_URL, "-v", "ON_ERROR_STOP=1", "-q", "-c", "DELETE FROM workers WHERE hourly_rate_cents <= 0"]);

    // WHAT HOIV LOOKED LIKE BEFORE, read from the real row.
    const before = q(
      `SELECT active || '|' || coalesce(lat::text,'-') || '|' || coalesce(lng::text,'-') || '|' || slug FROM locations WHERE id = '${WALL_TAG_UUID}'`,
    );
    assert.ok(before.startsWith("true|"), `HOIV must be ACTIVE in the dump, found: ${before}`);
    ok(`before 006: HOIV is ${before}`);
    // Counted BEFORE, so "the migrations invent no zone" is a delta and not an assumption
    // about how old the dump is.
    const zonesBefore = q("SELECT count(*) FROM zones WHERE to_regclass('public.zones') IS NOT NULL");

    // WHICH FILES ARE PENDING DEPENDS ON THE AGE OF THE DUMP, and both ages are real: the
    // dump taken before a deploy window has 006-010 pending; the dump taken after it has
    // only the newest. So the pending set is READ OFF THE RESTORED DATABASE rather than
    // hardcoded — a hardcoded list turns "this dump is newer than I expected" into a
    // failure that looks like a schema bug.
    const applied = new Set(
      q("SELECT filename FROM schema_migrations ORDER BY filename")
        .split("\n")
        .map((s) => s.trim())
        .filter(Boolean),
    );
    const ALL = [
      "006_zones_revenue_rates.sql",
      "007_operator_identity.sql",
      "008_reported_tags.sql",
      "009_phone_pending.sql",
      "010_zone_verification.sql",
    ];
    const pending = ALL.filter((f) => !applied.has(f));
    assert.ok(
      pending.includes("010_zone_verification.sql"),
      "010 must be PENDING in the dump under test — a dump that already has it proves nothing about applying it",
    );
    const out = sh("node", [MIGRATE], { env: { ...process.env, DATABASE_URL } });
    for (const f of pending) {
      assert.match(out, new RegExp(`applied ${f.replace(/\./g, "\\.")}`), `${f} must apply`);
    }
    ok(`applied, in order, over the client's own rows: ${pending.join(", ")}`);

    // ---- THE ROW ITSELF ---------------------------------------------------------------
    assert.equal(
      q(`SELECT active || '|' || coalesce(lat::text,'-') || '|' || coalesce(lng::text,'-') || '|' || slug FROM locations WHERE id = '${WALL_TAG_UUID}'`),
      before,
      "006 changed HOIV's row — it must leave it exactly as it found it, coordinates included",
    );
    assert.equal(q("SELECT count(*) FROM zones"), zonesBefore, "no migration may invent (or destroy) a zone");
    assert.equal(
      q(`SELECT count(*) FROM zones WHERE location_id = '${WALL_TAG_UUID}'`),
      "0",
      "HOIV must have ZERO zones in the dump under test — that is the production fact the wall-card tap below is about, and a dump with zones cannot make the claim",
    );
    ok("after migrating: the row is byte-identical, the zone count is unchanged, and HOIV still has ZERO zones");

    // ---- THE API, AND THE TWO WORDS -----------------------------------------------------
    process.env.DATABASE_URL = DATABASE_URL;
    process.env.APP_KEY = APP_KEY;
    process.env.PORT = "0";

    // A worker with a REAL rate, because 006 makes any other kind unrepresentable. The raw
    // cookie is 64 hex characters and the ROW stores only its SHA-256 (lib/auth.js), so
    // neither fixture credential below can become replayable even if it leaked.
    const workerToken = randomBytes(32).toString("hex");
    const adminToken = randomBytes(32).toString("hex");
    const hash = (t) => createHash("sha256").update(t, "utf8").digest("hex");
    q(`INSERT INTO workers (name, hourly_rate_cents) VALUES ('HOIV Check', 1500)`);
    q(
      `INSERT INTO worker_sessions (token, worker_id, expires_at)
       SELECT '${hash(workerToken)}', id, now() + interval '1 hour' FROM workers WHERE name = 'HOIV Check'`,
    );
    q(
      `INSERT INTO sessions (token, admin_id, expires_at)
       SELECT '${hash(adminToken)}', id, now() + interval '1 hour' FROM admins ORDER BY id LIMIT 1`,
    );

    const { createServer, assertEnv } = await import(path.join(SERVER, "server.js"));
    assertEnv();
    server = createServer();
    await new Promise((r) => server.listen(0, "127.0.0.1", r));
    const base = `http://127.0.0.1:${server.address().port}`;
    const call = (p, opts = {}) =>
      fetch(base + p, {
        method: opts.method ?? "GET",
        headers: {
          "X-App-Key": APP_KEY,
          Cookie: opts.as === "admin" ? `ts_session=${adminToken}` : `ts_worker=${workerToken}`,
          ...(opts.body ? { "Content-Type": "application/json" } : {}),
        },
        body: opts.body ? JSON.stringify(opts.body) : undefined,
      });
    ok("the API booted against the restored, migrated production database");

    // *** THE LINE THAT MUST NEVER BE DELETED FOR TIDINESS. ***
    // The shipped APK's exact request shape, with the uuid off the card on the wall, at a
    // building with no zones at all. 422 here means the tag is dead and no site visit fixes it.
    const clientUuid = "11111111-2222-4333-8444-5555555590a1";
    const opened = await call("/shifts/open", {
      method: "POST",
      body: { client_uuid: clientUuid, location_uuid: WALL_TAG_UUID, start_time: new Date().toISOString() },
    });
    const body = await opened.json();
    assert.equal(opened.status, 201, `THE CARD ON THE WALL MUST STILL CLOCK A WORKER IN: ${JSON.stringify(body)}`);
    assert.equal(body.shift.location_id, WALL_TAG_UUID);
    assert.equal(body.shift.start_zone_id, null, "a building tag records NO zone and must not invent one");
    assert.equal(
      (await call("/shifts/close", { method: "POST", body: { client_uuid: clientUuid, end_time: new Date(Date.now() + 60_000).toISOString() } })).status,
      200,
    );
    ok("POST /shifts/open with the WALL CARD's uuid at an UNZONED building -> 201");

    // *** THE SAME CARD, WITH AN UNVERIFIED ZONE NOW SITTING UNDER IT (decision-47). ***
    // This is the shape production takes the day somebody creates HOIV's first zone. The
    // wall card must answer IDENTICALLY — same status, same location_id, same NULL zone —
    // because verification is a ZONE-only concept and a building tap reads no zone at all.
    // A zone under this building is deliberately created with NO verified_at, which is what
    // 010 makes the default state of every zone.
    q(`INSERT INTO zones (location_id, name) VALUES ('${WALL_TAG_UUID}', 'Erste Zone, ungepr\u00fcft')`);
    assert.equal(
      q(`SELECT count(*) FROM zones WHERE location_id = '${WALL_TAG_UUID}' AND verified_at IS NULL AND active`),
      "1",
      "the fixture must be an ACTIVE, UNVERIFIED zone, or the assertion below proves nothing",
    );
    const withZone = "11111111-2222-4333-8444-5555555590a2";
    const zoned = await call("/shifts/open", {
      method: "POST",
      body: { client_uuid: withZone, location_uuid: WALL_TAG_UUID, start_time: new Date().toISOString() },
    });
    const zonedBody = await zoned.json();
    assert.equal(
      zoned.status,
      201,
      `THE CARD ON THE WALL MUST STILL CLOCK A WORKER IN, with an unverified zone under it: ${JSON.stringify(zonedBody)}`,
    );
    assert.equal(zonedBody.shift.location_id, WALL_TAG_UUID);
    assert.equal(zonedBody.shift.start_zone_id, null, "a building tag must not acquire the zone somebody just created");
    assert.equal(
      (await call("/shifts/close", { method: "POST", body: { client_uuid: withZone, end_time: new Date(Date.now() + 60_000).toISOString() } })).status,
      200,
      "and the clock-out is never gated either",
    );
    // A tap on THAT ZONE's own id, by contrast, IS refused — which is what makes the
    // assertion above a statement about the BUILDING branch and not about a dead gate.
    const zoneId = q(`SELECT id FROM zones WHERE location_id = '${WALL_TAG_UUID}'`);
    const zoneTap = await call("/shifts/open", {
      method: "POST",
      body: { client_uuid: "11111111-2222-4333-8444-5555555590a3", location_uuid: zoneId, start_time: new Date().toISOString() },
    });
    assert.equal(zoneTap.status, 422, "an UNVERIFIED zone's own id must be refused");
    assert.equal((await zoneTap.json()).error, "zone_unverified", "...by name");
    q(`DELETE FROM shifts WHERE client_uuid = '${withZone}'`);
    q(`DELETE FROM zones WHERE location_id = '${WALL_TAG_UUID}'`);
    ok("the WALL CARD is unchanged with an UNVERIFIED zone under it, while that zone's own id is refused");

    // *** THE FIXTURE SHIFT IS DELETED BEFORE ANY MAP SURFACE IS READ, AND THAT IS LOAD-
    // BEARING. *** `reportableLocations` lists a building that is active OR was worked in the
    // period. Leaving the tap above in place makes the second branch true, so a mutant that
    // deletes the FIRST branch — the naive rule "only zoned buildings are real buildings" —
    // still finds HOIV on the map and the check passes vacuously. Production has ZERO shifts:
    // HOIV must appear because it is ACTIVE, which is exactly the claim being made.
    q(`DELETE FROM shifts WHERE client_uuid = '${clientUuid}'`);
    assert.equal(q("SELECT count(*) FROM shifts"), "0", "the map assertions below must read a database with NO shifts, like production");

    // The two words, on every surface that reports them. A single `active: l.active && zoned`
    // anywhere is the whole mistake, so all of them are read rather than one and a hope.
    const now = Date.now();
    const period = `from=${new Date(now - 86_400_000).toISOString()}&to=${new Date(now + 86_400_000).toISOString()}`;
    const analytics = (await (await call(`/admin/analytics?${period}`, { as: "admin" })).json()).buildings.find(
      (b) => b.location_id === WALL_TAG_UUID,
    );
    assert.ok(analytics, "HOIV must appear in /admin/analytics at all — a vanished building is the other failure");
    assert.equal(analytics.zone_state, "unzoned", "HOIV has no zones, and the map must SAY so");
    assert.equal(analytics.active, true, "/admin/analytics must report the OPERATIONAL active, not 'has zones'");

    // /admin/pl takes the same required from/to range as /admin/analytics (`v.requiredRange`
    // — both ends, refusing beats guessing), not a month.
    const plRow = (await (await call(`/admin/pl?${period}`, { as: "admin" })).json()).buildings.find(
      (b) => b.location_id === WALL_TAG_UUID,
    );
    assert.ok(plRow, "HOIV must appear in /admin/pl");
    assert.equal(plRow.active, true, "/admin/pl must report the OPERATIONAL active");
    assert.equal(plRow.zone_state, "unzoned");
    assert.equal(plRow.building_m2, null, "no zones -> no area, and never 0 (a 0 is a division waiting to happen)");
    assert.equal(plRow.area_unknown_reason, "no_zones", "...and the reason is NAMED, not implied by a blank");

    const dataRow = (await (await call("/admin/data", { as: "admin" })).json()).locations.find((l) => l.id === WALL_TAG_UUID);
    assert.equal(dataRow.active, true, "/admin/data must report the OPERATIONAL active");
    ok("zone_state 'unzoned' + active true on /admin/analytics, /admin/pl and /admin/data");

    // THE PIN STILL DRAWS. Grey is a colour, not an absence: decision-39 makes the map the
    // landing surface, and a building that loses its coordinates loses the whole screen.
    assert.match(String(analytics.lat), /^\d+\.\d+$/, "HOIV must still carry a latitude for the map to pin it");
    assert.match(String(analytics.lng), /^\d+\.\d+$/, "...and a longitude");
    ok(`the pin still draws, grey: ${analytics.name} @ ${analytics.lat}/${analytics.lng}`);

    // And the roster the phone caches still names it.
    const roster = await (await call("/roster")).json();
    assert.ok(roster.locations.some((l) => l.id === WALL_TAG_UUID), "GET /roster must still serve HOIV");
    assert.ok(Array.isArray(roster.zones) && roster.zones.length === 0, "zones[] is present and empty");
    ok("GET /roster still serves HOIV; zones[] is additive and empty");

    console.log("\nOK check-hoiv-survives-006: HOIV survives 006 active, pinned, unzoned and TAPPABLE.");
  } finally {
    if (server) await new Promise((r) => server.close(r));
    const { pool } = await import(path.join(SERVER, "lib", "db.js")).catch(() => ({ pool: null }));
    if (pool) await pool.end().catch(() => {});
    try {
      sh("dropdb", ["--force", "--if-exists", DB_NAME]);
    } catch {
      console.error(`warning: could not drop ${DB_NAME}`);
    }
  }
}

// =========================================================================================
// PHASE 2 — the mutants. Each is the naive rule, wired into a different place.
// =========================================================================================
async function mutants() {
  const runCore = () => spawnSync("node", [fileURLToPath(import.meta.url), "--core", DUMP], { encoding: "utf8" });

  const MUTANTS = [
    {
      name: "activePlace() gains a zone predicate — decision-37's rule wired into RESOLUTION",
      file: path.join(SERVER, "lib", "validate.js"),
      from: "      WHERE l.id = $1 AND l.active\n     UNION ALL",
      to: "      WHERE l.id = $1 AND l.active AND EXISTS (SELECT 1 FROM zones z0 WHERE z0.location_id = l.id AND z0.active)\n     UNION ALL",
      expect: /THE CARD ON THE WALL MUST STILL CLOCK A WORKER IN/,
    },
    {
      name: "the two words merged — reportableLocations reports `active AND zoned` as `active`",
      file: path.join(SERVER, "lib", "reporting.js"),
      from: "SELECT l.id, l.slug, l.name, l.address, l.active, l.lat, l.lng,",
      to: "SELECT l.id, l.slug, l.name, l.address, (l.active AND EXISTS (SELECT 1 FROM zones z9 WHERE z9.location_id = l.id AND z9.active)) AS active, l.lat, l.lng,",
      expect: /must report the OPERATIONAL active/,
    },
    {
      // decision-47's FIRST way to kill the same card: the gate's building early-return
      // deleted. Every building-level tap in the system then reads `zone_verified_at` —
      // which is a literal NULL on that branch — and 422s. HOIV's card dies instantly.
      name: "the verification gate loses its BUILDING early return — decision-47's first mutant",
      file: path.join(SERVER, "lib", "validate.js"),
      from: "  if (place.zone_id === null) return place; // BUILDING TAP. No zone exists, so no gate can apply.\n",
      to: "",
      expect: /THE CARD ON THE WALL MUST STILL CLOCK A WORKER IN/,
    },
    {
      // decision-47's SECOND way: verification wired into RESOLUTION rather than named at
      // the clock-in site. The building branch starts requiring a VERIFIED zone to exist,
      // so the wall card at an unzoned building — or at one whose only zone is unproven —
      // resolves to nothing.
      name: "activePlace's building branch requires a VERIFIED zone — decision-47's second mutant",
      file: path.join(SERVER, "lib", "validate.js"),
      from: "      WHERE l.id = $1 AND l.active\n     UNION ALL",
      to: "      WHERE l.id = $1 AND l.active AND EXISTS (SELECT 1 FROM zones z7 WHERE z7.location_id = l.id AND z7.verified_at IS NOT NULL)\n     UNION ALL",
      expect: /THE CARD ON THE WALL MUST STILL CLOCK A WORKER IN/,
    },
    {
      // THE OTHER WAY IT DIES: not greyed, GONE. `reportableLocations` is what puts a pin on
      // the map at all (decision-39 makes the map the landing surface), so a zone predicate
      // in its WHERE removes the client's only building from the only screen the director
      // opens — and nothing on that screen can then say why.
      name: "HOIV VANISHES — reportableLocations requires a zone to list a building at all",
      file: path.join(SERVER, "lib", "reporting.js"),
      from: "      WHERE l.active\n         OR EXISTS (SELECT 1 FROM shifts s WHERE s.location_id = l.id AND ${IN_PERIOD})",
      to: "      WHERE (l.active AND EXISTS (SELECT 1 FROM zones z8 WHERE z8.location_id = l.id AND z8.active))\n         OR EXISTS (SELECT 1 FROM shifts s WHERE s.location_id = l.id AND ${IN_PERIOD})",
      expect: /must appear in \/admin\/analytics at all/,
    },
  ];

  console.log("== baseline (must be GREEN before any mutant means anything)");
  const baseline = runCore();
  process.stdout.write(baseline.stdout);
  if (baseline.status !== 0) {
    process.stderr.write(baseline.stderr);
    console.error("BASELINE IS RED — fix that first; no mutant below means anything.");
    process.exit(1);
  }

  let red = 0;
  let alive = 0;
  for (const m of MUTANTS) {
    const original = fs.readFileSync(m.file, "utf8");
    if (!original.includes(m.from)) {
      console.log(`DEAD  ${m.name} — mutation site not found in ${path.basename(m.file)}`);
      alive++;
      continue;
    }
    fs.writeFileSync(m.file, original.replace(m.from, m.to));
    try {
      const r = runCore();
      const output = `${r.stdout}\n${r.stderr}`;
      if (r.status === 0) {
        console.log(`ALIVE ${m.name} — the mutant PASSED. The assertion does not fire.`);
        alive++;
      } else if (!m.expect.test(output)) {
        console.log(`WRONG ${m.name} — it failed, but not on the assertion this mutant targets.`);
        console.log(output.split("\n").filter((l) => /FAIL|Assertion|Error/.test(l)).slice(0, 3).join("\n"));
        alive++;
      } else {
        console.log(`RED   ${m.name}`);
        red++;
      }
    } finally {
      // ALWAYS restore, even on a throw: a mutant left on disk is a source file quietly
      // rewritten by a check, which is worse than the defect it was hunting.
      fs.writeFileSync(m.file, original);
    }
  }

  console.log("== the tree is restored; re-running must be GREEN again");
  const after = runCore();
  if (after.status !== 0) {
    process.stdout.write(after.stdout);
    process.stderr.write(after.stderr);
    console.error("STILL RED after revert — a mutant was not restored cleanly.");
    process.exit(1);
  }
  const dirty = spawnSync("git", ["diff", "--quiet", "--", path.join(SERVER, "lib")], { encoding: "utf8" });
  if (dirty.status !== 0) {
    console.error("server/lib is NOT byte-identical to HEAD after this run — restore it by hand.");
    process.exit(1);
  }

  console.log(`\nmutants: ${red} red, ${alive} alive-or-dead`);
  if (alive > 0) process.exit(1);
  console.log("OK check-hoiv-survives-006: HOIV survives 006-010, and all FIVE ways of killing it are RED.");
}

await (CORE ? core() : mutants());
