// The two RED-case generators. Both operate on the REAL file's text — never a hand-typed
// stand-in — via a substring that only exists once, so a future edit to reset-w1.sql that
// moves or rewords the guard makes this throw LOUDLY (a stale check silently proving
// nothing) rather than silently checking the wrong thing.
function onceOnly(haystack, needle, what) {
  const first = haystack.indexOf(needle);
  assert.notEqual(first, -1, `${what}: marker not found in ops/reset-w1.sql — this check is stale`);
  assert.equal(haystack.indexOf(needle, first + 1), -1, `${what}: marker is not unique in ops/reset-w1.sql`);
  return first;
}

/** AC#2 RED: the live-code guard's IF neutralised to `IF false THEN` — nothing else touched. */
function withLiveCodeGuardDisabled() {
  const needle = "IF n_live_codes > 0 AND current_setting('reset_w1.allow_live_code_loss', true) <> '1' THEN";
  onceOnly(RESET_SQL, needle, "AC#2 live-code guard");
  return RESET_SQL.replace(needle, "IF false THEN");
}

/** AC#3 RED: the whole admins-survives assertion block (section 5) deleted outright. */
function withAdminsGuardRemoved() {
  const startMarker = "-- 5 · THE ASSERTION THAT MATTERS";
  const endMarker = "\\echo 'AFTER:'";
  const start = onceOnly(RESET_SQL, startMarker, "AC#3 assertion block start");
  const end = onceOnly(RESET_SQL, endMarker, "AC#3 assertion block end");
  assert.ok(start < end, "AC#3: assertion block markers are out of order — this check is stale");
  return RESET_SQL.slice(0, start) + RESET_SQL.slice(end);
}

/** AC#5 RED: section 4's phone_identities detach removed — the ONE piece of this script
 * that is not in decision-46's sketch, because it was found by walking the FK graph 007
 * introduces. Without it, `DELETE FROM workers` drives a worker-only registry row to
 * (NULL, NULL) mid-statement and phone_identities_claims aborts the whole transaction.
 * A fix nobody has watched fail is a fix nobody knows is load-bearing. */
function withPhoneDetachRemoved() {
  const startMarker = "DO $$ BEGIN\n  IF to_regclass('public.phone_identities') IS NOT NULL THEN";
  const endMarker = "DELETE FROM workers;";
  const start = onceOnly(RESET_SQL, startMarker, "AC#5 RED detach block start");
  const end = onceOnly(RESET_SQL, endMarker, "AC#5 RED detach block end");
  assert.ok(start < end, "AC#5 RED: detach block markers are out of order — this check is stale");
  return RESET_SQL.slice(0, start) + RESET_SQL.slice(end);
}

/** AC#3 GREEN companion: the REAL script, PLUS an unrelated "mistake elsewhere" DELETE FROM
 * admins, to prove the real assertion catches a mistake it did not itself introduce. */
function withAnExtraAdminsDeleteElsewhere() {
  const needle = "DELETE FROM locations;";
  const at = onceOnly(RESET_SQL, needle, "AC#3 GREEN insertion point");
  const insertAt = at + needle.length;
  return (
    RESET_SQL.slice(0, insertAt) +
    "\nDELETE FROM admins; -- injected by check-reset-w1.mjs: a mistake ELSEWHERE in a hand-edited copy" +
    RESET_SQL.slice(insertAt)
  );
}

let dbCounter = 0;
const scratchDbs = [];
function newDbName(tag) {
  const name = `nfc_resetw1_${tag}_${process.pid}_${dbCounter++}`;
  scratchDbs.push(name);
  return name;
}

const psql = (dbName, sql) =>
  sh("psql", [`postgres:///${dbName}`, "-v", "ON_ERROR_STOP=1", "-q", "-t", "-A", "-c", sql]).trim();
const countOf = (dbName, sql) => Number(psql(dbName, sql));

/** Run a (possibly mutated) reset-w1.sql script text against a scratch DB.
 * @returns {{ok: boolean, stdout: string, stderr: string}} never throws. */
function runReset(dbName, sqlText, extraArgs = []) {
  const tmp = path.join("/tmp", `check-reset-w1-${dbName}.sql`);
  fs.writeFileSync(tmp, sqlText);
  try {
    const stdout = sh("psql", [
      `postgres:///${dbName}`,
      "-v",
      "ON_ERROR_STOP=1",
      "-v",
      `confirm_database=${dbName}`,
      ...extraArgs,
      "-f",
      tmp,
    ]);
    return { ok: true, stdout, stderr: "" };
  } catch (e) {
    return { ok: false, stdout: String(e.stdout ?? ""), stderr: String(e.stderr ?? e.message) };
  } finally {
    fs.rmSync(tmp, { force: true });
  }
}

/** A fully migrated (001-007) scratch DB, one admin, optionally seeded further by `seed`.
 * `admin: false` is for AC#8, where the admin row arrives with the dump and inventing a
 * second one would make "the owner survived" pass on a row this file wrote. */
function freshDb(tag, { migrate = true, admin = true } = {}) {
  const name = newDbName(tag);
  sh("createdb", [name]);
  if (migrate) sh("node", [MIGRATE], { env: { ...process.env, DATABASE_URL: `postgres:///${name}` } });
  if (admin) psql(name, "INSERT INTO admins (email, password_hash) VALUES ('reset-check@example.test', 'x')");
  return name;
}

